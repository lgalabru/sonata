#!/usr/bin/env python3
"""Writes Sources/SonataCore/LandMaskData.swift: a 720x360 land bitmap (0.5 degree cells,
row 0 at 90N, column 0 at 180W, bits packed most significant first), rasterized from Natural
Earth's 1:110m land polygons, which are in the public domain.

A cell is land when at least half of it is: the polygons are filled at 4x resolution, then
each cell's coverage is averaged.

Usage:
  curl -LO https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson
  python3 scripts/gen-landmask.py ne_110m_land.geojson     (needs Pillow)
"""
import base64, json, os, sys
from PIL import Image, ImageDraw

W, H, SS = 720, 360, 4
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "Sources/SonataCore/LandMaskData.swift")


def polygons(geometry):
    if geometry["type"] == "Polygon":
        yield geometry["coordinates"]
    elif geometry["type"] == "MultiPolygon":
        yield from geometry["coordinates"]


def to_pixels(ring):
    return [((lon + 180) / 360 * W * SS, (90 - lat) / 180 * H * SS) for lon, lat in ring]


def main(path):
    with open(path) as f:
        land = json.load(f)
    big = Image.new("L", (W * SS, H * SS), 0)
    draw = ImageDraw.Draw(big)
    for feature in land["features"]:
        for exterior, *holes in polygons(feature["geometry"]):
            draw.polygon(to_pixels(exterior), fill=255)
            for hole in holes:
                draw.polygon(to_pixels(hole), fill=0)
    cells = big.resize((W, H), Image.BOX)  # mean coverage per cell
    px = cells.load()
    packed = bytearray(W * H // 8)
    for row in range(H):
        for col in range(W):
            if px[col, row] >= 128:
                i = row * W + col
                packed[i >> 3] |= 0x80 >> (i & 7)
    b64 = base64.b64encode(bytes(packed)).decode()
    lines = "\n".join(b64[i:i + 120] for i in range(0, len(b64), 120))
    with open(OUT, "w") as f:
        f.write(
            "// Generated by scripts/gen-landmask.py from Natural Earth's 1:110m land polygons (public domain).\n"
            "// 720x360 cells of 0.5 degrees, row 0 at 90N, column 0 at 180W, bits packed most significant first.\n\n"
            f'let landMaskBase64 = """\n{lines}\n"""\n'
        )
    print(f"wrote {OUT}: {sum(bin(b).count('1') for b in packed)} land cells")


if __name__ == "__main__":
    main(sys.argv[1])
